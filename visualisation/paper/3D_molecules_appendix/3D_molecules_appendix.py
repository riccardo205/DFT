#!/usr/bin/env python3
"""
Appendix figures: PyMOL renders of the lowest broken-symmetry state of every fitted dimer, assembled into a
few full-page figures (NROWS x NCOLS panels each) that are imported in LaTeX as single images.

Inputs
  SUMMARY_CSV  bs_summary_all_runs.csv (Read_output_bs_orca.py): dimers, order (ascending r2SCAN-3c relaxation
               energy, as in Table tab:bs_summary_all_runs), short name (2_c7) and magnetic family label
  RENDER_CSV   bs_ground_states.csv (render_bs_ground_states.py): lowest-energy configuration of every dimer
  RENDER_DIR   renders/<run>_<dimer>/<config>.png (render_bs_ground_states.py)

Output (OUT_DIR, upload the folder to Overleaf)
  3D_molecules_page<k>.pdf / .png   one page each, white margins of the renders cropped, every panel labelled
                                    "2_c7 (FM)" with the family in its table colour. The last page is cut to
                                    the rows it uses. The .tex uses the PDFs if all pages together are
                                    <= MAX_PDF_TOTAL_MB, otherwise the PNGs.
  3D_molecules_appendix.tex         one figure per page; pages after the first are \\ContinuedFloat.
In the paper: \\usepackage{graphicx,caption} and \\input{3D_molecules_appendix/3D_molecules_appendix.tex}
(paths in the tex relative to the main .tex: set TEX_PREFIX).

Settings in the `if __name__ == "__main__":` block.
"""

import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
from Read_output_bs_orca import FAMILY_STYLE  # noqa: E402   (letter, label, colour) per family
from render_bs_ground_states import trim_white  # noqa: E402


def collect(summary_csv, render_csv, render_dir):
    """Table rows in table order with the render PNG of their lowest-energy configuration."""
    S = pd.read_csv(summary_csv)
    G = pd.read_csv(render_csv)
    G["key"] = G["run"] + "/" + G["dimer"]
    S = S.merge(G[["key", "ground_state_config"]], on="key", how="left")
    S["png"] = [render_dir / k.replace("/", "_") / f"{c}.png" for k, c in zip(S["key"], S["ground_state_config"])]
    ok = S["png"].map(lambda p: p.exists())
    if (~ok).any():
        print(f"[!] no render, skipped: {', '.join(S.loc[~ok, 'key'])} (run render_bs_ground_states.py)")
    return S[ok].reset_index(drop=True)


def coloured_label(fig, ax, name, family, y, size, renderer):
    """'name (family)' centred below the panel, family in its colour (bold)."""
    _, lab, col = FAMILY_STYLE.get(str(family)[:1], (None, "", "000000"))
    parts = [(name + (" (" if lab else ""), "black", "normal")]
    if lab:
        parts += [(lab, f"#{col}", "bold"), (")", "black", "normal")]
    texts = [ax.text(0.5, y, s, transform=ax.transAxes, ha="left", va="top", fontsize=size, color=c,
                     fontweight=w, clip_on=False) for s, c, w in parts]
    widths = [t.get_window_extent(renderer).width for t in texts]
    x0 = ax.transAxes.transform((0.5, 0))[0] - sum(widths) / 2
    inv = ax.transAxes.inverted()
    for t, wd in zip(texts, widths):
        t.set_x(inv.transform((x0, 0))[0])
        x0 += wd


def make_pages(S, out_dir, nrows, ncols, page_w, page_h, label_size, label_gap, wspace, hspace, crop_pad, dpi,
               font):
    plt.rcParams.update({"font.family": font, "pdf.fonttype": 42})
    per_page = nrows * ncols
    row_h = page_h / nrows
    files = []
    for k, start in enumerate(range(0, len(S), per_page), 1):
        page = S.iloc[start:start + per_page]
        used_rows = -(-len(page) // ncols)
        fig = plt.figure(figsize=(page_w, row_h * used_rows))
        bottom = (label_size * 1.8 / 72) / fig.get_figheight()          # room for the labels of the last row
        gs = fig.add_gridspec(used_rows, ncols, left=0, right=1, top=1, bottom=bottom, wspace=wspace, hspace=hspace)
        renderer = fig.canvas.get_renderer()
        for i, (_, r) in enumerate(page.iterrows()):
            ax = fig.add_subplot(gs[i // ncols, i % ncols])
            ax.imshow(trim_white(plt.imread(r["png"]), pad=crop_pad), interpolation="antialiased")
            ax.set_anchor("S")                     # image at the bottom of its cell, label right under it
            ax.axis("off")
        fig.canvas.draw()
        for i, (_, r) in enumerate(page.iterrows()):
            ax = fig.axes[i]
            coloured_label(fig, ax, r["name"], r["mag_family"], -label_gap, label_size, renderer)
        stem = out_dir / f"3D_molecules_page{k}"
        fig.savefig(f"{stem}.pdf", dpi=dpi)
        fig.savefig(f"{stem}.png", dpi=dpi)
        plt.close(fig)
        files.append(stem)
    return files


def write_tex(stems, ext, tex_path, tex_prefix, caption, label):
    out = ["% generated by visualisation/paper/3D_molecules_appendix.py; needs graphicx, caption"]
    for k, stem in enumerate(stems):
        out += [r"\begin{figure}[p]"] + ([r"\ContinuedFloat"] if k else []) + [
            r"\centering",
            rf"\includegraphics[width=\textwidth,height=0.92\textheight,keepaspectratio]{{{tex_prefix}{stem.name}.{ext}}}",
            rf"\caption{{{caption}}}\label{{{label}}}" if k == 0 else r"\caption[]{(continued)}",
            r"\end{figure}", ""]
    tex_path.write_text("\n".join(out))


def main(summary_csv, render_csv, render_dir, out_dir, nrows, ncols, page_w, page_h, label_size, label_gap, wspace,
         hspace, crop_pad, dpi, font, max_pdf_total_mb, tex_prefix, caption, label):
    out_dir.mkdir(parents=True, exist_ok=True)
    for f in out_dir.glob("3D_molecules_page*"):
        f.unlink()
    S = collect(summary_csv, render_csv, render_dir)
    stems = make_pages(S, out_dir, nrows, ncols, page_w, page_h, label_size, label_gap, wspace, hspace, crop_pad,
                       dpi, font)
    size = {e: sum(Path(f"{s}.{e}").stat().st_size for s in stems) / 1e6 for e in ("pdf", "png")}
    ext = "pdf" if size["pdf"] <= max_pdf_total_mb else "png"
    write_tex(stems, ext, out_dir / "3D_molecules_appendix.tex", tex_prefix, caption, label)
    print(f"{len(S)} dimers, {nrows} x {ncols} per page -> {len(stems)} pages in {out_dir}\n"
          f"  pdf {size['pdf']:.1f} MB, png {size['png']:.1f} MB -> tex uses {ext}")


if __name__ == "__main__":
    # =========================
    # USER SETTINGS
    # =========================
    VIS = HERE.parent
    SUMMARY_CSV = VIS / "output" / "orca" / "dimers_run2" / "bs_summary_all_runs.csv"
    BS_GS_DIR = VIS / "pymol_rendered_cmap" / "orca" / "dimers_run2" / "bs_ground_states"
    RENDER_CSV = BS_GS_DIR / "bs_ground_states.csv"
    RENDER_DIR = BS_GS_DIR / "renders"
    OUT_DIR = HERE / "3D_molecules_appendix"

    NROWS, NCOLS = 8, 4                # panels per page
    PAGE_W, PAGE_H = 6.3, 9.0           # inches of a full page (= \textwidth x usable \textheight of the paper)
    LABEL_SIZE = 8                      # pt (the figure is included at \textwidth, so this is the printed size)
    LABEL_GAP = 0.02                    # label distance below the panel (fraction of the panel height)
    WSPACE, HSPACE = 0.04, 0.22         # gaps between panels (fractions of the panel width / height)
    CROP_PAD = 6                        # px of white kept around each cropped render
    DPI = 300
    FONT = "serif"                      # label font
    MAX_PDF_TOTAL_MB = 20               # tex uses the PDFs if all pages together are at most this, else the PNGs
    TEX_PREFIX = "3D_molecules_appendix/"   # path of OUT_DIR as seen from the main .tex in Overleaf
    LABEL = "fig:3d_molecules_appendix"
    CAPTION = (r"Lowest-energy broken-symmetry state (PBE0) of every dimer of "
               r"Table~\ref{tab:bs_summary_all_runs}, in the same order (ascending r2SCAN-3c energy). Molecules "
               r"in green and purple; spheres coloured by Mulliken spin, arrows on atoms with "
               r"$|\mathrm{spin}|>0.15$ (red up, blue down, length $\propto|\mathrm{spin}|$); hydrogens hidden. "
               r"Label: dimer and magnetic family.")

    main(SUMMARY_CSV, RENDER_CSV, RENDER_DIR, OUT_DIR, NROWS, NCOLS, PAGE_W, PAGE_H, LABEL_SIZE, LABEL_GAP, WSPACE,
         HSPACE, CROP_PAD, DPI, FONT, MAX_PDF_TOTAL_MB, TEX_PREFIX, CAPTION, LABEL)
