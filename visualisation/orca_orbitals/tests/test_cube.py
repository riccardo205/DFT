"""Cube parser: formats, units, voxel ordering, non-orthogonal grids, malformed files."""

import tempfile
import unittest
from pathlib import Path

import numpy as np

from orca_orbitals.cube import BOHR_TO_ANGSTROM, Cube, CubeFormatError, read_cube, write_cube

REAL_ORCA_CUBE = (Path(__file__).resolve().parents[3] /
                  "runs/orca/short-2OS/angle_scans/visualization_orbitals/M1/broken_symmetry/F0/broken_symmetry.mo177a.cube")

# 2 x 2 x 3 grid written by hand in Gaussian order (i3 fastest), value = 100*i1 + 10*i2 + i3
CONVENTIONAL = """comment 1
comment 2
    2    0.000000    0.000000    0.000000
    2    0.500000    0.000000    0.000000
    2    0.000000    0.400000    0.000000
    3    0.000000    0.000000    0.300000
    6    6.000000    0.000000    0.000000    0.000000
    1    1.000000    2.000000    0.000000    0.000000
  0.0 1.0 2.0
  10.0 11.0 12.0
  100.0 101.0 102.0
  110.0 111.0 112.0
"""

# ORCA layout: negative atom count, '1 <MO>' record, 6 values per line ignoring row boundaries
ORCA_STYLE = """Cube data generated by ORCA
Molecular orbital 7 of operator 1
   -1   -1.000000   -1.000000   -1.000000
    2    1.000000    0.000000    0.000000
    2    0.000000    1.000000    0.000000
    3    0.000000    0.000000    1.000000
    8    8.000000    0.000000    0.000000    0.000000
    1    7
   0.00000E+00   1.00000E+00   2.00000E+00   1.00000E+01   1.10000E+01   1.20000E+01
   1.00000E+02   1.01000E+02   1.02000E+02   1.10000E+02   1.11000E+02   1.12000E+02
"""


def _write(text):
    d = tempfile.mkdtemp()
    p = Path(d) / "t.cube"
    p.write_text(text)
    return p


class CubeParsing(unittest.TestCase):
    def check_ordering(self, c):
        for i in range(2):
            for j in range(2):
                for k in range(3):
                    self.assertEqual(c.data[i, j, k], 100 * i + 10 * j + k)

    def test_conventional(self):
        c = read_cube(_write(CONVENTIONAL))
        self.assertEqual(c.shape, (2, 2, 3))
        self.assertEqual(c.orbital_ids, ())
        self.assertEqual(list(c.atomic_numbers), [6, 1])
        np.testing.assert_allclose(c.positions[1], [2, 0, 0])
        self.check_ordering(c)
        np.testing.assert_allclose(c.grid_to_cartesian([1, 1, 2]), [0.5, 0.4, 0.6])

    def test_orca_negative_atom_count(self):
        c = read_cube(_write(ORCA_STYLE))
        self.assertEqual(c.orbital_ids, (7,))
        self.assertEqual(c.orca_mo(), (7, 1))
        self.assertEqual(len(c.atomic_numbers), 1)
        self.check_ordering(c)
        np.testing.assert_allclose(c.origin, [-1, -1, -1])

    def test_angstrom_units(self):
        text = CONVENTIONAL.replace("    2    0.5", "   -2    0.5").replace("    2    0.000000    0.4", "   -2    0.000000    0.4") \
                           .replace("    3    0.000000    0.000000    0.3", "   -3    0.000000    0.000000    0.3")
        c = read_cube(_write(text))
        np.testing.assert_allclose(c.axes[0], [0.5 / BOHR_TO_ANGSTROM, 0, 0])
        np.testing.assert_allclose(c.positions[1], [2 / BOHR_TO_ANGSTROM, 0, 0])
        self.check_ordering(c)

    def test_multi_orbital_record_wraps_lines(self):
        ids = tuple(range(100, 112))     # 12 ids -> record spans two lines
        rng = np.random.default_rng(0)
        data = rng.normal(size=(3, 2, 2, 12))
        cube = Cube(("multi", "MO"), np.zeros(3), np.eye(3) * 0.3, np.array([1]), np.array([1.0]),
                    np.zeros((1, 3)), data, ids)
        p = Path(tempfile.mkdtemp()) / "m.cube"
        write_cube(p, cube)
        self.assertGreaterEqual(len(p.read_text().splitlines()[7].split()), 2)
        c = read_cube(p)
        self.assertEqual(c.orbital_ids, ids)
        self.assertEqual(c.n_values, 12)
        np.testing.assert_allclose(c.volume(5), data[..., 5], atol=1e-4)

    def test_non_orthogonal_voxels_map_to_cartesian(self):
        axes = np.array([[0.20, 0.00, 0.00], [0.08, 0.25, 0.00], [0.05, -0.04, 0.30]])
        origin = np.array([-1.0, 0.5, 2.0])
        shape = (5, 6, 7)
        idx = np.stack(np.meshgrid(*[np.arange(n) for n in shape], indexing="ij"), axis=-1)
        xyz = origin + idx @ axes
        f = xyz[..., 0] + 10 * xyz[..., 1] + 100 * xyz[..., 2]        # known function of position
        cube = Cube(("c", "c"), origin, axes, np.array([6]), np.array([6.0]), np.zeros((1, 3)), f)
        p = Path(tempfile.mkdtemp()) / "n.cube"
        write_cube(p, cube, angstrom=True)
        c = read_cube(p)
        self.assertFalse(c.is_orthogonal())
        grid = c.cartesian_grid()
        np.testing.assert_allclose(c.data, grid[..., 0] + 10 * grid[..., 1] + 100 * grid[..., 2], rtol=1e-4, atol=1e-3)

    def test_too_many_values(self):
        with self.assertRaisesRegex(CubeFormatError, "found 13 volumetric values, expected 12"):
            read_cube(_write(CONVENTIONAL + "  999.0\n"))

    def test_too_few_values(self):
        with self.assertRaisesRegex(CubeFormatError, "found 9"):
            read_cube(_write(CONVENTIONAL.replace("  110.0 111.0 112.0\n", "")))

    def test_orca_count_mismatch_not_silently_truncated(self):
        # 12 values but the record claims 2 orbitals -> 24 expected; must not take "the last N"
        with self.assertRaisesRegex(CubeFormatError, "orbital record|expected 24"):
            read_cube(_write(ORCA_STYLE.replace("    1    7", "    2    7    8")))

    def test_malformed(self):
        cases = {
            "empty": "",
            "mixed units": CONVENTIONAL.replace("    2    0.5", "   -2    0.5"),
            "bad atom": CONVENTIONAL.replace("    1    1.000000    2.000000    0.000000    0.000000", "    1    1.0  2.0"),
            "zero points": CONVENTIONAL.replace("    3    0.000000    0.000000    0.3", "    0    0.000000    0.000000    0.3"),
            "text data": CONVENTIONAL.replace("110.0", "abc"),
            "missing record": ORCA_STYLE.replace("    1    7\n", "    3    7\n"),
        }
        for name, text in cases.items():
            with self.subTest(name), self.assertRaises(CubeFormatError):
                read_cube(_write(text))

    @unittest.skipUnless(REAL_ORCA_CUBE.exists(), "user-generated ORCA cube not available")
    def test_real_orca_cube(self):
        c = read_cube(REAL_ORCA_CUBE)
        self.assertEqual(c.orca_mo(), (177, 0))
        self.assertEqual(c.orbital_ids, (177,))
        self.assertEqual(len(c.atomic_numbers), 86)
        self.assertEqual(c.shape, (40, 40, 40))


if __name__ == "__main__":
    unittest.main()
